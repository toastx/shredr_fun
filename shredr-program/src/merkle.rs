//! Incremental Merkle tree over note commitments.
//!
//! The pool used to keep every commitment in an array and scan it on each spend.
//! That put a hard lifetime cap on deposits and made the scan grow with the pool,
//! which is backwards — a pool wants to be as large as possible, because its size
//! *is* its privacy.
//!
//! A tree fixes both. Deposits are bounded by `2^DEPTH` rather than by what fits
//! in an account, the on-chain state is a fixed [`DEPTH`] nodes regardless of how
//! many notes exist, and a spend costs [`DEPTH`] hashes instead of one comparison
//! per note in the pool.
//!
//! The leaves themselves are never stored on chain. They do not need to be:
//! deposits are public base-layer transactions, so anyone can replay them to
//! rebuild the tree and produce a path. That is the client's job, and the
//! backend can serve the leaf list as a convenience without learning anything —
//! it is public data either way.
//!
//! ## Insertion
//!
//! The standard incremental construction. `filled_subtrees[i]` is the left
//! sibling waiting at level `i` for its right-hand partner; everything to the
//! right of the frontier is empty, and an empty subtree at level `i` hashes to
//! [`ZEROS`]`[i]`. So appending a leaf touches exactly one node per level.
//!
//! ## Verification
//!
//! A spender supplies the leaf index and one sibling per level. The index's bits
//! say which side each sibling goes on, which is why the index is not stored
//! anywhere on the base layer — it identifies the exact deposit, and only the
//! enclave ever sees it.

use crate::errors::ShredrError;
use crate::note::sha256;
use pinocchio::error::ProgramError;

/// Tree height, so 1,048,576 notes per pool.
