/// `sha256(left || right)`.
fn hash_pair(left: &[u8; 32], right: &[u8; 32]) -> [u8; 32] {
    sha256(&[left, right])
}

/// Append `leaf`, returning the new root.
///
/// `filled_subtrees` and `next_index` are the whole tree: everything to the right
/// of the frontier is empty by definition, so there is nothing else to store.
pub fn insert(
    filled_subtrees: &mut [[u8; 32]; DEPTH],
    next_index: u64,
    leaf: &[u8; 32],
) -> Result<[u8; 32], ProgramError> {
    if next_index >= capacity() {
        return Err(ShredrError::PoolTreeFull.into());
    }

    let mut index = next_index;
    let mut current = *leaf;

    for (level, subtree) in filled_subtrees.iter_mut().enumerate() {
        current = if index.is_multiple_of(2) {
            // First of a pair: park it and hash against the empty right half.
            *subtree = current;
            hash_pair(&current, &ZEROS[level])
        } else {
            hash_pair(subtree, &current)
        };
        index /= 2;
    }

    Ok(current)
}

/// Recompute the root that `leaf` implies, given its index and one sibling per
/// level.
///
/// Returns a root rather than a bool so the caller decides what to compare it
/// against — which matters, because the pool accepts any recent root and not
/// only the current one.
pub fn root_from_path(
    leaf: &[u8; 32],
    leaf_index: u64,
    path: &[[u8; 32]; DEPTH],
) -> [u8; 32] {
    let mut current = *leaf;

    for (level, sibling) in path.iter().enumerate() {
        current = if (leaf_index >> level) & 1 == 0 {
            hash_pair(&current, sibling)
        } else {
            hash_pair(sibling, &current)
        };
    }

    current
}

/// Leaves the tree can hold.
pub const fn capacity() -> u64 {
    1u64 << DEPTH
}

/// The root of a tree with nothing in it.
pub fn empty_root() -> [u8; 32] {
    hash_pair(&ZEROS[DEPTH - 1], &ZEROS[DEPTH - 1])
}
